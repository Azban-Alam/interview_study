package String_Class_Methods;

public class Imp__Method_charAt {

	// charAt() : Returns the character at the specified index (position)

	public static void main(String[] args) {

		String s1 = "Hello";

		char c1 = s1.charAt(0);
		System.out.println(c1);

		char c2 = s1.charAt(2);
		System.out.println(c2);
	}

}
